"use strict";
const fs = require("node:fs");
const path = require("node:path");
const assert = require("node:assert/strict");
const root = path.resolve(__dirname, "..");
const read = (file) =>
  JSON.parse(fs.readFileSync(path.join(root, "data", file), "utf8"));
const countries = read("natural-earth-countries.geojson");
const places = read("natural-earth-places.geojson");
const data = {
  countries: {
    type: "FeatureCollection",
    features: countries.features.map((f) => ({
      type: "Feature",
      geometry: f.geometry,
      properties: {
        name: f.properties.NAME,
        rank: f.properties.LABELRANK,
        label: [f.properties.LABEL_Y, f.properties.LABEL_X],
      },
    })),
  },
  places: places.features.map((f) => ({
    name: f.properties.name,
    lat: f.geometry.coordinates[1],
    lon: f.geometry.coordinates[0],
    minZoom: f.properties.min_zoom,
  })),
};
const content =
  "// Natural Earth public-domain geography; generated by build-geography.cjs.\nwindow.ATLAS_GEOGRAPHY = " +
  JSON.stringify(data).replaceAll("<", "\\u003c") +
  ";\n";
const file = path.join(root, "assets/geography.js");
if (process.argv.includes("--check"))
  assert.equal(fs.readFileSync(file, "utf8"), content);
else fs.writeFileSync(file, content);
console.log(
  `Geography: ${data.countries.features.length} countries, ${data.places.length} place labels.`,
);
