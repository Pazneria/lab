export function resourceSources(entry, field, folder) {
  if (!Object.hasOwn(entry,field)) return "'none'";
  const paths=entry[field], admitted=approvedResources[entry.id]?.[field];
  if (!Array.isArray(paths)||!paths.length||!admitted||paths.length!==admitted.length) throw Error('Unapproved host resources');
  const base=new URL(folder);
  if (!['https:','http:'].includes(base.protocol)||base.search||base.hash||base.username||base.password||!base.pathname.endsWith(`/entries/${entry.id}/frozen/`)) throw Error('Invalid frozen folder');
  return paths.map((path,index)=>{
    if (typeof path!=='string'||!path.split('/').every(part=>/^[A-Za-z0-9_-][A-Za-z0-9_.-]*$/.test(part)&&part!=='.'&&part!=='..')||path!==admitted[index].relativePath) throw Error('Unapproved resource path');
    const url=new URL(path,base);
    if (url.origin!==base.origin||!url.pathname.startsWith(base.pathname)||url.search||url.hash) throw Error('Resource escaped frozen folder');
    return url.href;
  }).join(' ');
}
export function scenePolicy(entry,folder) {
  const dataStyles=entry.allowDataStyles===true?'data: ':'';
  return `default-src 'none'; script-src 'unsafe-inline' ${folder}; style-src 'unsafe-inline' ${dataStyles}${folder}; img-src data: blob: ${folder}; font-src ${resourceSources(entry,'hostFontAssets',folder)}; connect-src ${resourceSources(entry,'hostFetchAssets',folder)}; media-src 'none'; worker-src 'none'; frame-src 'none'; object-src 'none'; form-action 'none'; base-uri ${folder}`;
}
